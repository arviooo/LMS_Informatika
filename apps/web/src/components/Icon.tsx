export interface IconProps extends React.SVGProps<SVGSVGElement> {
  name: string;
  className?: string;
  size?: number | string;
  color?: string;
}

export default function Icon({ name, className = '', size, color, ...props }: IconProps) {
  const mappedName = iconMapping[name];
  
  if (!mappedName) {
    console.warn(`Icon "${name}" is missing mapping. Using default HelpCircle.`);
  }

  // Fallback to HelpCircle if not found
  const IconComponent = (LucideIcons[mappedName || 'HelpCircle'] as React.ElementType) || LucideIcons.HelpCircle;

  // Handle animate-spin manually if we need to replace it
  const isSpin = className.includes('animate-spin') || name === 'progress_activity' || name === 'sync';
  
  let finalClassName = className;
  // if spin is needed but not in className, we might add it? 
  // Let's just trust the original className.

  return <IconComponent className={finalClassName} size={size} color={color} {...props} />;
}
